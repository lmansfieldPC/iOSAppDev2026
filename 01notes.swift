// ===== Lesson 1: Variables and Constants =====


// ----- print -----
print("Hello, world!")
print(7 + 3)
print("Hello", "world", 42)


// ----- comments -----
// this whole line is ignored
print("this runs")   // this part is ignored


// ----- var: a value you can change -----
var score = 10
print(score)              // 10

score = 25
print(score)              // 25

score = score + 5
print(score)              // 30


// ----- let: a value you cannot change -----
let schoolName = "Penn Charter"
print(schoolName)         // Penn Charter

// let birthYear = 2009
// birthYear = 2010       // uncomment: what is the error?


// ----- initialize once, reassign as often as you want -----
var color = "blue"
// var color = "red"      // uncomment: what is the error?
color = "red"             // this is fine
print(color)              // red


// ----- naming rules -----
var myFavoriteNumber = 17     // camelCase
// var 2cool = "nope"         // uncomment: what is the error?
// var my favorite = "nope"   // uncomment: what is the error?
print(myFavoriteNumber)


